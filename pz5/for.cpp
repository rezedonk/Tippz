#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian"); // Чтобы русские буквы в консоли не были крякозябрами
    double X, Y;
    
    cout << "Введите начальную сумму X: ";
    cin >> X;
    cout << "Введите пороговую сумму Y: ";
    cin >> Y;
    
    double current_sum = X;
    int day = 0;
    
    // Бесконечный цикл for
    for (;;) {
        day++; // Сначала наступает новый день
        
        // Проверяем условие ФНС
        if (current_sum >= Y) {
            break; // Если сумма уже достигла цели, выходим из цикла
        }
        
        // Если не достигли, увеличиваем сумму на 10% для следующего дня
        // Но подожди, логика дня: в 1-й день он отмыл X. 
        // Если X < Y, то на 2-й день сумма будет X * 1.1.
        // Значит, проверку на >= Y мы делаем в начале дня.
        
        // Давай перепишем логику чуть чище:
        // День 1: сумма = X.
        // Если сумма < Y, то день 2: сумма = сумма * 1.1.
        
        if (current_sum >= Y) {
            // Мы уже проверили выше, но чтобы не дублировать, сделаем так:
        }
        
        // Исправляем логику для for:
        // Мы должны проверять условие в начале каждой итерации.
        // Но если мы используем break, то структура такая:
        
        if (current_sum >= Y) {
            break;
        }
        
        current_sum *= 1.1; // Увеличиваем на 10% для следующего дня
    }
    
    cout << "Номер дня: " << day << endl;
    return 0;
}
