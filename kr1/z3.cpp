#include <iostream>

using namespace std;

int main() {
    // Подключаем русский язык для корректного отображения в консоли
    setlocale(LC_ALL, "Russian");

    // Объявляем переменные с плавающей точкой, так как коэффициенты дробные
    double a, b, c;
    double result;

    // Блок ввода данных
    cout << "Введите значение a: ";
    cin >> a;
    cout << "Введите значение b: ";
    cin >> b;
    cout << "Введите значение c: ";
    cin >> c;

    // Блок вычислений
    // Используем упрощенное выражение: 9.6a + 5.6b - 16.8c
    // Это позволяет избежать лишних операций умножения и раскрытия скобок в коде
    result = 9.6 * a + 5.6 * b - 16.8 * c;

    // Блок вывода результата
    cout << "Значение выражения: " << result << endl;

    return 0;
}
